"""Rebuild the small public similarity matrix; model weights stay in HF's cache.

Requires Python with torch and transformers. Run from any working directory:
    python scripts/prepare-embeddings.py
"""

import json
from pathlib import Path

import torch
import torch.nn.functional as F
from transformers import AutoModel, AutoTokenizer

MODEL = "sentence-transformers/all-MiniLM-L6-v2"
REVISION = "1110a243fdf4706b3f48f1d95db1a4f5529b4d41"
WORDS = [
    "APRICOT", "TUBA", "SUBPOENA", "NEBULA",
    "MANGO", "CELLO", "VERDICT", "QUASAR",
    "PLUM", "OBOE", "AFFIDAVIT", "GALAXY",
    "LEMON", "HARP", "INJUNCTION", "PULSAR",
]


def main():
    tokenizer = AutoTokenizer.from_pretrained(MODEL, revision=REVISION)
    model = AutoModel.from_pretrained(MODEL, revision=REVISION)
    model.eval()
    tokens = tokenizer([word.lower() for word in WORDS], padding=True, truncation=True, return_tensors="pt")
    with torch.no_grad():
        output = model(**tokens)[0]
        mask = tokens["attention_mask"].unsqueeze(-1).expand(output.size()).float()
        pooled = torch.sum(output * mask, 1) / torch.clamp(mask.sum(1), min=1e-9)
        vectors = F.normalize(pooled, p=2, dim=1)
        matrix = vectors @ vectors.T
    similarities = [[round(float(value), 7) for value in row] for row in matrix]
    for index in range(len(WORDS)):
        similarities[index][index] = 1.0
    info = {
        "name": MODEL,
        "revision": REVISION,
        "url": f"https://huggingface.co/{MODEL}",
        "license": "Apache-2.0",
        "dimensions": 384,
        "method": "Lowercase isolated words; attention-mask mean pooling; L2 normalization; cosine similarity.",
        "note": "Model-based relatedness is a game rule, not an objective measure of meaning. This sentence model was applied experimentally to isolated words.",
    }
    output_path = Path(__file__).resolve().parents[1] / "games" / "anti-connections" / "data.js"
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(
        "// Generated by scripts/prepare-embeddings.py. See DATA.md for provenance.\n"
        'export const BOARD_ID = "first-orbit-v1";\n'
        f"export const WORDS = Object.freeze({json.dumps(WORDS)});\n"
        f"export const MODEL_INFO = Object.freeze({json.dumps(info, indent=2)});\n"
        "export const SIMILARITIES = Object.freeze([\n"
        + ",\n".join("  Object.freeze(" + json.dumps(row) + ")" for row in similarities)
        + "\n]);\n",
        encoding="utf-8",
    )
    print(f"Wrote {output_path.name}: {len(WORDS)} words, {len(WORDS) * (len(WORDS) - 1) // 2} actual cosine similarities.")
    print(f"Model revision: {REVISION}")


if __name__ == "__main__":
    main()
